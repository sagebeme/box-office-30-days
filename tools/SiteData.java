import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Writes site/assets/days.js, the course website's list of phases and days,
 * from the root README.md and each day's README.md. Run it from the repo root
 * after changing a README:
 *
 * <pre>
 * java tools/SiteData.java           writes site/assets/days.js
 * java tools/SiteData.java --check   fails if days.js is out of date (CI runs this)
 * </pre>
 *
 * One file, no libraries: Java 21 runs it straight from the source.
 */
public class SiteData {

    static final Path OUT = Path.of("site/assets/days.js");

    // ### Phase 1 · Days 101–105 · Foundations for real software
    static final Pattern PHASE = Pattern.compile("^### Phase (\\d+) · Days (\\d+)–(\\d+) · (.+)$");
    // - [Day 101](day-101-project-skeleton): Project skeleton and CI (Maven wrapper, modules, JUnit, AssertJ)
    static final Pattern DAY = Pattern.compile("^- \\[Day (\\d+)]\\(([^)]+)\\): (.+?)(?: \\((.+)\\))?$");
    static final Pattern TITLE = Pattern.compile("^# Day \\d+: (.+)$");
    static final Pattern TICK = Pattern.compile("^- \\[ ] (.+)$");

    record Phase(int n, String name, String about, int first, int last) {
    }

    record Day(int day, int phase, String path, String title, String topic, String scene, String brief,
               List<String> checklist) {
    }

    public static void main(String[] args) throws IOException {
        boolean check = args.length > 0 && args[0].equals("--check");
        String js = render();
        if (check) {
            String now = Files.exists(OUT) ? Files.readString(OUT, StandardCharsets.UTF_8) : "";
            if (!now.equals(js)) {
                System.err.println(OUT + " is out of date: run java tools/SiteData.java and commit it");
                System.exit(1);
            }
            System.out.println(OUT + " is up to date");
            return;
        }
        Files.writeString(OUT, js, StandardCharsets.UTF_8);
        System.out.println("Wrote " + OUT);
    }

    static String render() throws IOException {
        List<String> lines = Files.readAllLines(Path.of("README.md"), StandardCharsets.UTF_8);
        List<Phase> phases = new ArrayList<>();
        List<Day> days = new ArrayList<>();
        for (int i = 0; i < lines.size(); i++) {
            Matcher phase = PHASE.matcher(lines.get(i));
            if (phase.matches()) {
                phases.add(new Phase(Integer.parseInt(phase.group(1)), phase.group(4).strip(), paragraphAfter(lines, i),
                        Integer.parseInt(phase.group(2)), Integer.parseInt(phase.group(3))));
                continue;
            }
            Matcher day = DAY.matcher(lines.get(i));
            if (day.matches() && !phases.isEmpty()) {
                days.add(readDay(Integer.parseInt(day.group(1)), phases.getLast().n(), day.group(2),
                        day.group(4) == null ? "" : day.group(4)));
            }
        }
        if (phases.isEmpty() || days.isEmpty()) {
            throw new IllegalStateException("README.md has no phases or days in the shape this tool reads");
        }

        StringBuilder js = new StringBuilder();
        js.append("// Generated by tools/SiteData.java from README.md and the day folders. Don't edit by hand.\n");
        js.append("window.BOX_PHASES = [\n");
        for (int i = 0; i < phases.size(); i++) {
            Phase p = phases.get(i);
            js.append("  {\"n\": ").append(p.n())
                    .append(", \"name\": ").append(json(p.name()))
                    .append(", \"about\": ").append(json(p.about()))
                    .append(", \"first\": ").append(p.first())
                    .append(", \"last\": ").append(p.last())
                    .append(i < phases.size() - 1 ? "},\n" : "}\n");
        }
        js.append("];\n");
        js.append("window.BOX_DAYS = [\n");
        for (int i = 0; i < days.size(); i++) {
            Day d = days.get(i);
            js.append("  {\n");
            js.append("    \"day\": ").append(d.day()).append(",\n");
            js.append("    \"phase\": ").append(d.phase()).append(",\n");
            js.append("    \"path\": ").append(json(d.path())).append(",\n");
            js.append("    \"title\": ").append(json(d.title())).append(",\n");
            js.append("    \"topic\": ").append(json(d.topic())).append(",\n");
            js.append("    \"scene\": ").append(json(d.scene())).append(",\n");
            js.append("    \"brief\": ").append(json(d.brief())).append(",\n");
            js.append("    \"checklist\": [");
            for (int j = 0; j < d.checklist().size(); j++) {
                js.append(j == 0 ? "\n      " : ",\n      ").append(json(d.checklist().get(j)));
            }
            js.append(d.checklist().isEmpty() ? "]\n" : "\n    ]\n");
            js.append(i < days.size() - 1 ? "  },\n" : "  }\n");
        }
        js.append("];\n");
        return js.toString();
    }

    static Day readDay(int number, int phase, String path, String topic) throws IOException {
        Path readme = Path.of(path, "README.md");
        if (!Files.exists(readme)) {
            throw new IllegalStateException("README.md links Day " + number + " to " + path + ", which has no README.md");
        }
        List<String> lines = Files.readAllLines(readme, StandardCharsets.UTF_8);
        Matcher title = TITLE.matcher(lines.getFirst());
        if (!title.matches()) {
            throw new IllegalStateException(readme + " should start with \"# Day " + number + ": Title\"");
        }
        String scene = lines.stream().filter(l -> l.startsWith("> ")).findFirst().map(l -> l.substring(2).strip()).orElse("");
        String brief = "";
        List<String> checklist = new ArrayList<>();
        for (int i = 0; i < lines.size(); i++) {
            if (lines.get(i).equals("## The brief")) {
                brief = firstSentences(paragraphAfter(lines, i), 220);
            }
            if (lines.get(i).equals("## Checklist")) {
                for (int j = i + 1; j < lines.size() && !lines.get(j).startsWith("## "); j++) {
                    Matcher tick = TICK.matcher(lines.get(j));
                    if (tick.matches()) {
                        checklist.add(tick.group(1).strip());
                    }
                }
            }
        }
        return new Day(number, phase, path, title.group(1).strip(), topic, scene, brief, checklist);
    }

    /** The first paragraph of plain text after line i, or "" if a list, heading or code comes first. */
    static String paragraphAfter(List<String> lines, int i) {
        int j = i + 1;
        while (j < lines.size() && lines.get(j).isBlank()) {
            j++;
        }
        StringBuilder text = new StringBuilder();
        while (j < lines.size() && !lines.get(j).isBlank() && !lines.get(j).matches("^(#|- |\\d+\\. |```|>|\\|).*")) {
            text.append(text.isEmpty() ? "" : " ").append(lines.get(j).strip());
            j++;
        }
        return text.toString();
    }

    /** Whole sentences, as many as fit in about max characters (always at least one). */
    static String firstSentences(String text, int max) {
        Matcher end = Pattern.compile("[.!?](?=\\s|$)").matcher(text);
        int cut = -1;
        while (end.find()) {
            if (cut != -1 && end.end() > max) {
                break;
            }
            cut = end.end();
        }
        return cut == -1 ? text : text.substring(0, cut);
    }

    static String json(String text) {
        StringBuilder out = new StringBuilder("\"");
        for (char c : text.toCharArray()) {
            switch (c) {
                case '"' -> out.append("\\\"");
                case '\\' -> out.append("\\\\");
                case '\n' -> out.append("\\n");
                case '<' -> out.append("\\u003c"); // never "</script>" inside a script
                default -> out.append(c < 0x20 ? String.format("\\u%04x", (int) c) : String.valueOf(c));
            }
        }
        return out.append('"').toString();
    }
}
